# Generates proto3ds/source/hud_font.h: a 128x128 4-bit alpha atlas (ASCII 32..126, cells 10x12, 12 per row)
# and the advance widths, from DejaVu Sans Bold 9 px (Bitstream Vera licence: free to embed).
import sys
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 9)
CW, CH, COLS = 10, 12, 12
atlas = Image.new("L", (128, 128), 0)
d = ImageDraw.Draw(atlas); d.fontmode = "L"
adv = []
for i in range(95):
    ch = chr(32 + i)
    d.text(((i % COLS) * CW + 1, (i // COLS) * CH + 9), ch, font=f, fill=255, anchor="ls")
    adv.append(max(3, round(f.getlength(ch))))
px = [v >> 4 for v in atlas.getdata()]
packed = [px[2 * k] | (px[2 * k + 1] << 4) for k in range(len(px) // 2)]
out = ["// Generated by tools/gen_hud_font.py from DejaVu Sans Bold 9 px (Bitstream Vera licence). Do not edit.",
       "#pragma once", "#include <stdint.h>", "",
       "#define HUD_FONT_ATLAS 128", "#define HUD_FONT_CELL_W 10", "#define HUD_FONT_CELL_H 12", "#define HUD_FONT_COLS 12",
       "#define HUD_FONT_BASELINE 9", "",
       "static const uint8_t kHudFontAdvance[95] = {" + ",".join(map(str, adv)) + "};", "",
       "// 4 bits of alpha per pixel, row-major, low nibble first (pixel p: byte p/2, low nibble when p is even).",
       "static const uint8_t kHudFontAlpha4[8192] = {"]
for i in range(0, len(packed), 24):
    out.append(",".join(str(v) for v in packed[i:i + 24]) + ",")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
