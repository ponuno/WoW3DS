# Generates proto3ds/source/ui_font_builtin.h: the 3DS client's own fonts (the stub skin of UI stage 7, used when
# ui.w3dp has no fonts): DejaVu Sans Bold at 9, 12 and 16 px (Bitstream Vera licence: free to embed), Latin +
# Cyrillic + the arrows and signs the UI draws, hinted by FreeType (PIL), one 4-bit alpha atlas 256 px wide.
#   python3 tools/gen_ui_font.py proto3ds/source/ui_font_builtin.h [font.ttf]
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[2] if len(sys.argv) > 2 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZES = [9, 12, 16]
W = 256
CPS = list(range(32, 127)) + [0xA0, 0xA9, 0xAB, 0xB0, 0xB7, 0xBB, 0xD7] + [0x401] + list(range(0x410, 0x450)) + [0x451] + \
      [0x2013, 0x2014, 0x2022, 0x2026, 0x2116, 0x2190, 0x2191, 0x2192, 0x2193, 0x25B2, 0x25B6, 0x25BC, 0x25C0, 0x25C6, 0x2709, 0x2713, 0x2715]

def main():
    fonts, glyphs, placed = [], [], []
    x = y = 0
    rowh = 0
    for size in SIZES:
        f = ImageFont.truetype(TTF, size)
        asc, desc = f.getmetrics()
        first = len(glyphs)
        for cp in CPS:
            ch = chr(cp)
            adv = max(1, round(f.getlength(ch)))
            l, t, r, b = f.getbbox(ch, anchor="ls")
            w, h = r - l, b - t
            if cp in (32, 0xA0) or w <= 0 or h <= 0:
                glyphs.append((cp, 0, 0, 0, 0, 0, 0, adv))
                continue
            img = Image.new("L", (w + 2, h + 2), 0)
            d = ImageDraw.Draw(img)
            d.fontmode = "L"
            d.text((1 - l, 1 - t), ch, font=f, fill=255, anchor="ls")
            bb = img.getbbox()
            if not bb:
                glyphs.append((cp, 0, 0, 0, 0, 0, 0, adv))
                continue
            img = img.crop(bb)
            gw, gh = img.size
            if x + gw + 1 > W:
                x = 0
                y += rowh + 1
                rowh = 0
            placed.append((x, y, img))
            glyphs.append((cp, x, y, gw, gh, l - 1 + bb[0], asc + t - 1 + bb[1], adv))
            x += gw + 1
            rowh = max(rowh, gh)
        fonts.append((size, asc + desc, asc, first, len(glyphs) - first))
    H = 8
    while H < y + rowh + 1:
        H *= 2
    atlas = Image.new("L", (W, H), 0)
    for (px, py, img) in placed:
        atlas.paste(img, (px, py))
    data = [v >> 4 for v in atlas.getdata()]
    packed = [data[2 * k] | (data[2 * k + 1] << 4) for k in range(len(data) // 2)]
    out = ["// Generated by tools/gen_ui_font.py from DejaVu Sans Bold %s px (Bitstream Vera licence). Do not edit." %
           "/".join(map(str, SIZES)),
           "// The stub skin's fonts (UI stage 7): Latin, Cyrillic, arrows; a %dx%d atlas of 4-bit alpha." % (W, H),
           "#pragma once", "#include <stdint.h>", "", '#include "w3d_ui.h"', "",
           "#define UI_FONT_BUILTIN_W %d" % W, "#define UI_FONT_BUILTIN_H %d" % H,
           "#define UI_FONT_BUILTIN_FONTS %d" % len(fonts), "#define UI_FONT_BUILTIN_GLYPHS %d" % len(glyphs), "",
           "static const W3dUiFont kUiFontBuiltin[%d] = {" % len(fonts)]
    for (size, lh, asc, first, n) in fonts:
        out.append("    {0, %d, %d, %d, {0, 0, 0}, %d, %d}," % (size, lh, asc, first, n))
    out.append("};")
    out.append("static const W3dUiGlyph kUiGlyphBuiltin[%d] = {" % len(glyphs))
    for (cp, gx, gy, gw, gh, xo, yo, adv) in glyphs:
        out.append("    {0x%X, %d, %d, %d, %d, %d, %d, %d, {0, 0, 0}}," % (cp, gx, gy, gw, gh, xo, yo, adv))
    out.append("};")
    out.append("// row-major, pixel p in byte p/2, low nibble when p is even")
    out.append("static const uint8_t kUiFontBuiltinA4[%d] = {" % len(packed))
    for i in range(0, len(packed), 32):
        out.append(",".join(str(v) for v in packed[i:i + 32]) + ",")
    out.append("};")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")
    print("atlas %dx%d, %d glyphs" % (W, H, len(glyphs)))

main()
