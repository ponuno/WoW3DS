"""gen_opcodes.py — the WoW Forever (Classic 1.60.1, builds 70291 and later) opcode numbers as the client sees them, from a
TrinityCore Forever fork's sources (src/server/game/Server/Protocol: Opcodes.h, ClassicOpcodes.cpp, ClassicClientOpcodes.inc).
The fork maps its retail core opcodes to the Classic numbers (TranslateServerOpcode / TranslateClientOpcode with the default
config: group shift 1, main-group insert indices 0x98 / 0x13B); this script does the same in Python and writes
net/forever/fopcodes.inc: { classic number, "NAME" } for the server's messages (SMSG) and the client's (CMSG).
  gen_opcodes.py <TrinityCore dir> <out.inc>"""
import re, sys, os
tc, out = sys.argv[1], sys.argv[2]
P = os.path.join(tc, 'src/server/game/Server/Protocol')
core = {}
for m in re.finditer(r'\b([CS]MSG_\w+)\s*=\s*(0x[0-9A-Fa-f]+)', open(os.path.join(P, 'Opcodes.h')).read()):
    core.setdefault(m.group(1), int(m.group(2), 16))
src = open(os.path.join(P, 'ClassicOpcodes.cpp')).read()
srv_over = {}
blk = re.search(r'ServerOpcodes\s*=\s*\{(.*?)\n\};', src, re.S).group(1)
for m in re.finditer(r'\{\s*(SMSG_\w+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}', blk):
    srv_over[m.group(1)] = int(m.group(2), 16)
blocked = set(re.findall(r'(SMSG_\w+),', re.search(r'BlockedServerOpcodes\s*=\s*\{(.*?)\n\};', src, re.S).group(1)))
cli70245 = {}   # classic 70245 number -> core
for m in re.finditer(r'\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}', open(os.path.join(P, 'ClassicClientOpcodes.inc')).read()):
    cli70245[int(m.group(1), 16)] = int(m.group(2), 16)

def grp(o): return o >> 16
def withg(o, g): return (g << 16) | (o & 0xFFFF)

def server70245(name, c):
    if name in srv_over: return srv_over[name]
    g = grp(c)
    if 0x45 <= g <= 0x6A:
        i = c & 0xFFFF
        if g == 0x45 and 0x17E <= i <= 0x1C0: i -= 1
        if g == 0x4A and i >= 4: i += 2
        if g == 0x51 and i >= 0x1C: i -= 1
        return ((g + 1) << 16) | i
    return c

def server(name, c):   # TranslateServerOpcode, shift 1
    o = server70245(name, c)
    g = grp(o)
    if g == 0x46 and (o & 0xFFFF) >= 0x98: o += 1
    g = grp(o)
    if 0x46 <= g <= 0x6B: o = withg(o, g + 1)
    return o

def client70245_of(c):   # inverse of TranslateClientOpcode70245 for a core number
    for k, v in cli70245.items():
        if v == c: return k
    g = grp(c)
    if 0x2A <= g <= 0x44: return withg(c, g + 1)   # the generic rule: classic group - 1 = core group
    return c

def client(c):   # inverse of TranslateClientOpcode with shift 1
    o = client70245_of(c)
    if grp(o) == 0x45: return withg(o, 0x46)           # the connection group moved
    if grp(o) == 0x44 and (o & 0xFFFF) > 0x13B - 1:    # one message inserted in the main group at 0x13B
        if (o & 0xFFFF) >= 0x13B: return o + 1
    return o

lines = ['// Generated by tools/forever/gen_opcodes.py from a TrinityCore Forever fork (Classic 1.60.1, builds 70291+). Do not edit.',
         '// { classic opcode, name } - server messages first, then the client\'s.', 'static const FOpcodeName kServerOpcodes[] = {']
seen = {}
for n, c in sorted(core.items(), key=lambda x: x[1]):
    if not n.startswith('SMSG_') or n in blocked or c == 0xBADD: continue
    o = server(n, c)
    if o in seen: continue
    seen[o] = n
    lines.append('    {0x%06X, "%s"},' % (o, n))
lines.append('};')
lines.append('static const FOpcodeName kClientOpcodes[] = {')
seen = {}
for n, c in sorted(core.items(), key=lambda x: x[1]):
    if not n.startswith('CMSG_') or c == 0xBADD: continue
    o = client(c)
    if o in seen: continue
    seen[o] = n
    lines.append('    {0x%06X, "%s"},' % (o, n))
lines.append('};')
open(out, 'w').write('\n'.join(lines) + '\n')
check = {n: server(n, core[n]) for n in ('SMSG_AUTH_CHALLENGE', 'SMSG_ENTER_ENCRYPTED_MODE', 'SMSG_AUTH_RESPONSE', 'SMSG_ENUM_CHARACTERS_RESULT',
                                          'SMSG_COMPRESSED_PACKET', 'SMSG_PONG', 'SMSG_SET_TIME_ZONE_INFORMATION', 'SMSG_ACCOUNT_DATA_TIMES')}
check.update({n: client(core[n]) for n in ('CMSG_AUTH_SESSION', 'CMSG_ENTER_ENCRYPTED_MODE_ACK', 'CMSG_ENUM_CHARACTERS', 'CMSG_PING',
                                           'CMSG_KEEP_ALIVE', 'CMSG_LOG_DISCONNECT')})
for k, v in check.items(): print('%-34s 0x%06X' % (k, v))
